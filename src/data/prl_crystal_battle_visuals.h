static const struct BattleEnvironment *GetCrystalBattleVisual(u8 environment)
{
    u32 i;
    u8 donor;

    if (environment >= BATTLE_ENVIRONMENT_COUNT)
        environment = BATTLE_ENVIRONMENT_PLAIN;
    if (!IS_FRLG)
        return &gBattleEnvironmentInfo[environment];

    donor = sCrystalDefaultVisuals[environment];
    // Location art overrides floors/arenas, never a surfing or underwater encounter.
    // Link/Frontier and legendary visuals keep their native special priority.
    if (!(gBattleTypeFlags & (BATTLE_TYPE_FRONTIER | BATTLE_TYPE_LINK | BATTLE_TYPE_RECORDED_LINK | BATTLE_TYPE_EREADER_TRAINER | BATTLE_TYPE_LEGENDARY))
        && environment != BATTLE_ENVIRONMENT_WATER
        && environment != BATTLE_ENVIRONMENT_POND
        && environment != BATTLE_ENVIRONMENT_UNDERWATER
        && (environment <= BATTLE_ENVIRONMENT_PLAIN
            || environment == BATTLE_ENVIRONMENT_GYM
            || environment == BATTLE_ENVIRONMENT_LEADER))
    {
        for (i = 0; i < ARRAY_COUNT(sCrystalMapVisuals); i++)
        {
            if (sCrystalMapVisuals[i].group == gSaveBlock1Ptr->location.mapGroup
                && sCrystalMapVisuals[i].number == gSaveBlock1Ptr->location.mapNum)
            {
                donor = sCrystalMapVisuals[i].donor;
                break;
            }
        }
    }
    return &sCrystalBattleVisuals[donor];
}
