static const struct PRLKantoCosmetic *PRLGetFinalKantoCosmetic(enum BattlerId battler, enum Species species)
{
#if IS_FRLG
    if (IsOnPlayerSide(battler) || !(gBattleTypeFlags & BATTLE_TYPE_TRAINER)
        || gBattleSpritesDataPtr->battlerData[battler].transformSpecies != SPECIES_NONE)
        return NULL;
    switch (TRAINER_BATTLE_PARAM.opponentA)
    {
    case TRAINER_PRL_BADGE_RECOVERY_BROCK:
        if (species == SPECIES_RHYDON) return &sPRLKanto_brock_rhydon;
        break;
    case TRAINER_PRL_BADGE_RECOVERY_MISTY:
        if (species == SPECIES_STARMIE && gBattlerPartyIndexes[battler] == 5) return &sPRLKanto_misty_starmie;
        break;
    case TRAINER_PRL_BADGE_RECOVERY_LT_SURGE:
        if (species == SPECIES_RAICHU) return &sPRLKanto_surge_raichu;
        break;
    case TRAINER_PRL_BADGE_RECOVERY_ERIKA:
        if (species == SPECIES_VICTREEBEL && gBattlerPartyIndexes[battler] == 5) return &sPRLKanto_erika_victreebel;
        break;
    case TRAINER_PRL_BADGE_RECOVERY_KOGA:
        if (species == SPECIES_NIDOQUEEN) return &sPRLKanto_nidoqueen_y;
        break;
    case TRAINER_PRL_BADGE_RECOVERY_SABRINA:
        if (species == SPECIES_ALAKAZAM) return &sPRLKanto_sabrina_alakazam;
        break;
    case TRAINER_PRL_BADGE_RECOVERY_BLAINE:
        if (species == SPECIES_ARCANINE && gBattlerPartyIndexes[battler] == 5) return &sPRLKanto_blaine_arcanine;
        break;
    case TRAINER_PRL_BADGE_RECOVERY_GIOVANNI:
        switch (species)
        {
        case SPECIES_TAUROS: return &sPRLKanto_tauros_x;
        case SPECIES_PINSIR: return &sPRLKanto_purakkusu_pinsir;
        case SPECIES_KABUTOPS: return &sPRLKanto_kabutops_p;
        case SPECIES_AERODACTYL: return &sPRLKanto_aerodactyl_p;
        case SPECIES_NIDOQUEEN: return &sPRLKanto_nidoqueen_y;
        case SPECIES_NIDOKING: return &sPRLKanto_nidoking_x;
        default: break;
        }
        break;
    case TRAINER_ELITE_FOUR_LORELEI:
        if (species == SPECIES_LAPRAS) return &sPRLKanto_lorelei_lapras;
        break;
    case TRAINER_ELITE_FOUR_BRUNO:
        if (species == SPECIES_MACHAMP) return &sPRLKanto_bruno_machamp;
        break;
    case TRAINER_ELITE_FOUR_AGATHA:
        if (species == SPECIES_GENGAR) return &sPRLKanto_shiny_mega_gengar;
        break;
    case TRAINER_ELITE_FOUR_LANCE:
        if (species == SPECIES_DRAGONITE) return &sPRLKanto_lance_dragonite;
        break;
    case TRAINER_CHAMPION_FIRST_SQUIRTLE:
    case TRAINER_CHAMPION_FIRST_BULBASAUR:
    case TRAINER_CHAMPION_FIRST_CHARMANDER:
        switch (species)
        {
        case SPECIES_PIDGEOT: return &sPRLKanto_mega_pidgeot;
        case SPECIES_ALAKAZAM: return &sPRLKanto_shiny_mega_alakazam;
        case SPECIES_NIDOKING: return &sPRLKanto_nidogod;
        case SPECIES_ARCANINE: return &sPRLKanto_champion_arcanine;
        default: break;
        }
        break;
    case TRAINER_JESSIE_JAMES_SILPH:
        if (species == SPECIES_WEEZING) return &sPRLKanto_rocket_weezing_blue;
        break;
    case TRAINER_JESSIE_JAMES_VICTORY_ROAD:
        if (species == SPECIES_WEEZING) return &sPRLKanto_rocket_weezing_fire;
        break;
    default: break;
    }
#endif
    return NULL;
}
